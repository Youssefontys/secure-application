"""Two-step verification: mandatory after the first password, logging in with the code, setting it up again and the
recovery code (MIT-05 to MIT-09, MIT-12). Runs through securitytest.py."""
from securitytest import *


def run():
    print("== mandatory two-step verification")
    c = client()
    req(c, "/register", {"username": "testacc1", "password": PW})
    r = req(c, "/login", {"username": "testacc1", "password": PW})
    check("login without 2FA", loc(r), "302 /account/2fa")
    check("  session cookie with SameSite=Lax and HttpOnly", ("SameSite=Lax" in r[2]["Set-Cookie"], "HttpOnly" in r[2]["Set-Cookie"]), (True, True))
    check("/ before the setup", loc(req(c, "/")), "302 /account/2fa")
    check("/account before the setup", loc(req(c, "/account")), "302 /account/2fa")
    check("create a note before the setup", loc(req(c, "/", {"title": "x", "body": "y"})), "302 /account/2fa")
    r = req(c, "/account/2fa")
    sec = secret(r[1])
    check("setup page", f"{r[0]} {r[2].get('Cache-Control')}", "200 no-store")
    check("reloading keeps the same secret", secret(req(c, "/account/2fa")[1]) == sec, True)
    check("qr.svg during the setup", req(c, "/account/2fa/qr.svg")[0], 200)
    check("wrong code at the setup", req(c, "/account/2fa", {"code": "000000"})[0], 400)
    r = req(c, "/account/2fa", {"code": fresh(sec, "testacc1")})
    rc = recovery(r[1])
    check("turning it on: recovery code shown", f"{r[0]} {len(rc)} {r[2].get('Cache-Control')}", "200 39 no-store")
    check("  Continue goes to the notes", re.search(r'id="recovery-done" href="([^"]+)"', r[1]).group(1), "/")
    check("then /", req(c, "/")[0], 200)
    check("qr.svg after turning it on", req(c, "/account/2fa/qr.svg")[0], 404)
    check("setup page after turning it on", loc(req(c, "/account/2fa")), "302 /account")
    check("logging out from the setup page works", loc(req(client(), "/logout", {})), "302 /login")

    print("== logging in")
    a = client()
    check("password", loc(req(a, "/login", {"username": "testacc1", "password": PW})), "302 /login/2fa")
    check("half login: /", loc(req(a, "/")), "302 /login")
    check("wrong code", req(a, "/login/2fa", {"code": "000000"})[0], 400)
    check("code with Arabic-Indic digits", req(a, "/login/2fa", {"code": "١٢٣٤٥٦"})[0], 400)
    check("right code", loc(req(a, "/login/2fa", {"code": fresh(sec, "testacc1")})), "302 /")
    r = req(client(), "/login", {"username": "testacc1", "password": "x"})
    check("login wrong password", (r[0], r[2]["WWW-Authenticate"], r[2]["Retry-After"]), (400, None, None))
    check("GET /login when logged in", loc(req(a, "/login")), "302 /")
    check("GET /register when logged in", loc(req(a, "/register")), "302 /")
    check("register twice", req(client(), "/register", {"username": "testacc1", "password": PW})[0], 409)

    print("== set up again, new recovery code")
    # The new recovery code on an account of its own: testacc1 then needs fewer codes in a short time.
    ad, secad, _ = account("testacc2")
    check("new recovery code with a wrong code", req(ad, "/account/2fa/recovery", {"current_password": PW, "code": "000000"})[0], 400)
    check("  with a good code but without the password (MC-29)", req(ad, "/account/2fa/recovery", {"code": fresh(secad, "testacc2")})[0], 400)
    r = req(ad, "/account/2fa/recovery", {"current_password": PW, "code": fresh(secad, "testacc2")})
    recovery(r[1])
    rc_before = rc
    check("new recovery code with password and code", f"{r[0]} {r[2].get('Cache-Control')}", "200 no-store")
    check("  Continue goes back to the profile", re.search(r'id="recovery-done" href="([^"]+)"', r[1]).group(1), "/account")
    a3 = login("testacc1", sec)
    check("set up again with a wrong code", req(a, "/account/2fa/reset", {"current_password": PW, "code": "000000"})[0], 400)
    check("  with a good code but without the password (MC-29)", (req(a, "/account/2fa/reset", {"code": fresh(sec, "testacc1")})[0],
          sql("SELECT totp_enabled FROM users WHERE username = 'testacc1'")), (400, "t"))
    check("set up again with password and code", loc(req(a, "/account/2fa/reset", {"current_password": PW, "code": fresh(sec, "testacc1")})),
          "302 /account/2fa")
    check("  then /", loc(req(a, "/")), "302 /account/2fa")
    check("  other session expires", loc(req(a3, "/")), "302 /login")
    sec = secret(req(a, "/account/2fa")[1])
    rc = recovery(req(a, "/account/2fa", {"code": fresh(sec, "testacc1")})[1])
    check("  set up anew", req(a, "/")[0], 200)

    print("== recovery code")
    h = password_step("testacc1")
    check("code page has a recovery link", 'href="/login/recover"' in req(h, "/login/2fa")[1], True)
    check("wrong recovery code", req(h, "/login/recover", {"code": "0" * 32})[0], 400)
    check("recovery code from before setting up again", req(h, "/login/recover", {"code": rc_before})[0], 400)
    check("right recovery code", loc(req(h, "/login/recover", {"code": " " + rc.upper() + " "})), "302 /account/2fa")
    check("  message", msg(req(h, "/account/2fa")[1]).startswith("Your recovery code has been used"), True)
    check("  then / without 2FA", loc(req(h, "/")), "302 /account/2fa")
    check("  other session expires", loc(req(a, "/")), "302 /login")
    check("  database: hash gone, 2FA off", sql("SELECT (recovery_hash IS NULL) || ',' || totp_enabled FROM users WHERE username='testacc1'"), "true,false")
